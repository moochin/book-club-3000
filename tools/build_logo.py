#!/usr/bin/env python3
"""Renders the boot-screen logo into firmware/src/logo_data.h (and art/logo.png).

The logo is "BOOK-CLUB" over "3000", set in Wide Glide (Brain Stew Fonts, 1997). The
font isn't in this repo: only its rendering is, so normal builds need neither
the font nor Pillow. Re-run this only to change the logo:

    pip install pillow
    python3 tools/build_logo.py [path/to/WideGlide.ttf]

Without a path it looks in the usual Windows font folders. The header holds a
4-bit coverage mask (0 = transparent, 15 = solid) that ui.cpp maps onto the
theme's colour ramp, so the logo follows the green/amber theme.
"""
import glob
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "firmware", "src", "logo_data.h")
PREVIEW = os.path.join(ROOT, "art", "logo.png")
LINES = ["BOOK-CLUB", "3000"]  # stacked: on one line the wide face is only 13 px tall
MAX_W, MAX_H = 304, 52        # fits the 320 px screen with a margin
GAP = 0.18                     # space between the lines, as a fraction of line height
SCALE = 8               # render big, then shrink: smooth edges


def find_font():
    if len(sys.argv) > 1:
        return sys.argv[1]
    pats = [os.path.expandvars(r"%LOCALAPPDATA%\Microsoft\Windows\Fonts\WideGlide*.ttf"),
            r"C:\Windows\Fonts\WideGlide*.ttf",
            os.path.expanduser("~/.fonts/WideGlide*.ttf"),
            os.path.expanduser("~/Library/Fonts/WideGlide*.ttf")]
    for p in pats:
        hits = glob.glob(p)
        if hits:
            return hits[0]
    sys.exit("Wide Glide not found: pass the .ttf path as an argument")


def render_line(font, text):
    l, t, r, b = font.getbbox(text)
    img = Image.new("L", (r - l + 4 * SCALE, b - t + 4 * SCALE), 0)
    ImageDraw.Draw(img).text((2 * SCALE - l, 2 * SCALE - t), text, font=font, fill=255)
    return img.crop(img.getbbox())


def render(path):
    font = ImageFont.truetype(path, 100 * SCALE)
    parts = [render_line(font, t) for t in LINES]
    gap = round(max(p.height for p in parts) * GAP)
    big = Image.new("L", (max(p.width for p in parts),
                          sum(p.height for p in parts) + gap * (len(parts) - 1)), 0)
    y = 0
    for p in parts:  # each line centred
        big.paste(p, ((big.width - p.width) // 2, y))
        y += p.height + gap
    k = min(MAX_W / big.width, MAX_H / big.height)
    return big.resize((max(1, round(big.width * k)), max(1, round(big.height * k))), Image.LANCZOS)


def main():
    img = render(find_font())
    w, h = img.size
    px = img.load()
    cov = [[(px[x, y] * 15 + 127) // 255 for x in range(w)] for y in range(h)]
    stride = (w + 1) // 2
    data = bytearray()
    for row in cov:
        row = row + [0] * (stride * 2 - w)
        for x in range(0, len(row), 2):
            data.append((row[x] << 4) | row[x + 1])
    lines = [
        "// GENERATED by tools/build_logo.py: \"BOOK-CLUB\" over \"3000\" in Wide Glide.",
        "// Do not edit; re-run the script instead.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "namespace logo {",
        "",
        f"constexpr int kW = {w};",
        f"constexpr int kH = {h};",
        "// 4-bit coverage, high nibble = left pixel, 0 = transparent, 15 = solid.",
        f"static const uint8_t kPx[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 24):
        lines.append("  " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",")
    lines += ["};", "", "}  // namespace logo", ""]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    # Preview in the green theme's colours.
    green = Image.new("RGB", (w + 16, h + 16), (0x03, 0x0C, 0x05))
    tint = Image.new("RGB", (w, h), (0xC0, 0xFF, 0xD0))
    green.paste(tint, (8, 8), img)
    green.save(PREVIEW)
    print(f"logo: {w}x{h} px, {len(data)} bytes -> firmware/src/logo_data.h, art/logo.png")


if __name__ == "__main__":
    main()
