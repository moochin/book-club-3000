#!/usr/bin/env python3
"""Writes src/mascot.js: the mascot from the units' setup page (art/mascot/
level0.png, thumbs up, in the green theme) as a PNG data URI for the hub's
web page. Run it again after redrawing that pose:

    python3 tools/make-mascot.py      (from worker/)
"""
import base64
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "tools"))
import build_art  # noqa: E402  (the same reader, palette and writer as the firmware)

src = os.path.join(build_art.ART_DIR, "level0.png")
w, h, rows = build_art.read_png(src)
idx = build_art.quantise("art/mascot/level0.png", rows)
pal = build_art.palette("green")
rgba = [[(0, 0, 0, 0) if i == 0 else (*pal[i], 255) for i in row] for row in idx]
with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as f:
    tmp = f.name
try:
    build_art.write_png(tmp, w, h, rgba)
    b64 = base64.b64encode(open(tmp, "rb").read()).decode()
finally:
    os.remove(tmp)
out = os.path.join(HERE, "..", "src", "mascot.js")
with open(out, "w") as f:
    f.write("// Generated by tools/make-mascot.py from art/mascot/level0.png: don't edit.\n")
    f.write(f'export const MASCOT = "data:image/png;base64,{b64}";\n')
print(f"wrote src/mascot.js ({w}x{h}, {len(b64)} base64 bytes)")
